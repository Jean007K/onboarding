export const dicts = { es, en, fr };

export function lookup(lang, key) {
  const table = dicts[lang] || es;
  const parts = key.split(".");
  let cur = table;
  for (const p of parts) {
    if (cur == null || typeof cur !== "object") return key;
    cur = cur[p];
  }
  if (typeof cur === "string") return cur;
  const fallback = parts.reduce((acc, p) => (acc == null ? acc : acc[p]), es);
  return typeof fallback === "string" ? fallback : key;
}

export function translateEstado(lang, estado) {
  if (!estado) return lookup(lang, "cruce.pendiente");
  const mapped = lookup(lang, `estado.${estado}`);
  return mapped === `estado.${estado}` ? estado : mapped;
}

export function translateCruceEstado(lang, estado) {
  const key = `cruce.${estado || "pendiente"}`;
  const v = lookup(lang, key);
  return v === key ? lookup(lang, "cruce.pendiente") : v;
}

export function fieldLabel(lang, campo, fallback) {
  const v = lookup(lang, `fields.${campo}`);
  return v === `fields.${campo}` ? fallback || campo : v;
}
